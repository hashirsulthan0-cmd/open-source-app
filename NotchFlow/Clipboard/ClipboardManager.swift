import AppKit
import CryptoKit

/// Watches the system clipboard and keeps a searchable history of what you copy.
///
/// macOS has no "clipboard changed" notification, so the pasteboard's change count is
/// checked every 0.4 seconds. Items are saved to Application Support and survive restarts.
@MainActor
final class ClipboardManager: ObservableObject {
    static let pollInterval: TimeInterval = 0.4
    static let maxUnpinnedItems = 200
    static let maxTextLength = 100_000

    /// Apps mark sensitive or temporary clipboard content with these types
    /// (see nspasteboard.org). Password managers use them, so NotchFlow never stores it.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = Set([
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
    ].map { NSPasteboard.PasteboardType($0) })

    @Published private(set) var items: [ClipboardItem]
    @Published var searchText = ""
    /// When false, new copies are ignored (the "Save clipboard history" setting).
    var isRecording = true

    private let pasteboard = NSPasteboard.general
    private let store = JSONFileStore<[ClipboardItem]>(
        url: AppPaths.supportDirectory.appendingPathComponent("clipboard.json")
    )
    private var lastChangeCount: Int
    private var timer: Timer?
    private var saveTask: Task<Void, Never>?

    init() {
        items = store.load() ?? []
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated {
                self?.checkPasteboard()
            }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        saveTask?.cancel()
        store.save(items)
    }

    /// Pinned items first, then newest first, filtered by the search text.
    var visibleItems: [ClipboardItem] {
        let sorted = items.sorted { lhs, rhs in
            lhs.isPinned != rhs.isPinned ? lhs.isPinned : lhs.copiedAt > rhs.copiedAt
        }
        let query = searchText.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !query.isEmpty else { return sorted }
        return sorted.filter { $0.searchableText.localizedCaseInsensitiveContains(query) }
    }

    // MARK: - Actions

    /// Puts an item back on the clipboard so it can be pasted.
    func copyToPasteboard(_ item: ClipboardItem) {
        pasteboard.clearContents()
        switch item.kind {
        case .text, .link:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            if let url = item.imageURL, let image = NSImage(contentsOf: url) {
                pasteboard.writeObjects([image])
            }
        case .files:
            pasteboard.writeObjects(item.fileURLs as [NSURL])
        }
        // Don't record our own write as a new copy, but do move the item to the top.
        lastChangeCount = pasteboard.changeCount
        update(item.id) { $0.copiedAt = Date() }
    }

    func togglePin(_ item: ClipboardItem) {
        update(item.id) { $0.isPinned.toggle() }
    }

    func delete(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        deleteImageIfUnused(item)
        scheduleSave()
    }

    /// Removes everything except pinned items.
    func clearUnpinned() {
        let removed = items.filter { !$0.isPinned }
        items.removeAll { !$0.isPinned }
        removed.forEach(deleteImageIfUnused)
        scheduleSave()
    }

    /// Removes everything, pinned items included.
    func clearAll() {
        let removed = items
        items.removeAll()
        removed.forEach(deleteImageIfUnused)
        scheduleSave()
    }

    // MARK: - Capturing

    private func checkPasteboard() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        guard isRecording else { return }

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes), let item = captureCurrentContents() else { return }
        insert(item)
    }

    private func captureCurrentContents() -> ClipboardItem? {
        let sourceApp = NSWorkspace.shared.frontmostApplication?.localizedName

        // Files first: Finder also puts icon images and names on the clipboard when copying files.
        if let urls = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            return ClipboardItem(
                kind: .files,
                filePaths: paths,
                sourceAppName: sourceApp,
                contentKey: "files:" + paths.joined(separator: "\n")
            )
        }

        if let pngData = currentImageAsPNG() {
            let hash = SHA256.hash(data: pngData).map { String(format: "%02x", $0) }.joined()
            let fileName = "\(hash).png"
            let url = AppPaths.clipboardImagesDirectory.appendingPathComponent(fileName)
            if !FileManager.default.fileExists(atPath: url.path) {
                do {
                    try pngData.write(to: url, options: .atomic)
                } catch {
                    NSLog("NotchFlow: could not save clipboard image: \(error.localizedDescription)")
                    return nil
                }
            }
            return ClipboardItem(
                kind: .image,
                imageFileName: fileName,
                sourceAppName: sourceApp,
                contentKey: "image:" + hash
            )
        }

        if let string = pasteboard.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let text = String(string.prefix(Self.maxTextLength))
            if let url = URL.webLink(from: text) {
                return ClipboardItem(
                    kind: .link,
                    text: url.absoluteString,
                    youTube: YouTubeLink.videoID(in: url).map { YouTubeMetadata(videoID: $0) },
                    sourceAppName: sourceApp,
                    contentKey: "link:" + url.absoluteString
                )
            }
            return ClipboardItem(kind: .text, text: text, sourceAppName: sourceApp, contentKey: "text:" + text)
        }

        return nil
    }

    private func currentImageAsPNG() -> Data? {
        if let png = pasteboard.data(forType: .png) {
            return png
        }
        guard let tiff = pasteboard.data(forType: .tiff),
              let bitmap = NSBitmapImageRep(data: tiff)
        else { return nil }
        return bitmap.representation(using: .png, properties: [:])
    }

    private func insert(_ newItem: ClipboardItem) {
        if let index = items.firstIndex(where: { $0.contentKey == newItem.contentKey }) {
            items[index].copiedAt = Date()
            items[index].sourceAppName = newItem.sourceAppName
            scheduleSave()
            return
        }

        items.insert(newItem, at: 0)
        trimHistory()
        scheduleSave()

        if let url = newItem.imageURL {
            recognizeText(for: newItem.id, imageURL: url)
        }
        if let videoID = newItem.youTube?.videoID, let link = newItem.text.flatMap(URL.init(string:)) {
            loadYouTubeMetadata(for: newItem.id, videoID: videoID, url: link)
        }
    }

    private func recognizeText(for id: UUID, imageURL: URL) {
        Task {
            guard let text = await TextRecognizer.recognizeText(inImageAt: imageURL) else { return }
            update(id) { $0.recognizedText = text }
        }
    }

    private func loadYouTubeMetadata(for id: UUID, videoID: String, url: URL) {
        Task {
            let metadata = await YouTubeMetadataLoader.load(videoID: videoID, url: url)
            update(id) { $0.youTube = metadata }
        }
    }

    // MARK: - Housekeeping

    private func update(_ id: UUID, _ change: (inout ClipboardItem) -> Void) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        change(&items[index])
        scheduleSave()
    }

    /// Keeps the newest `maxUnpinnedItems` unpinned items. Pinned items are never removed.
    private func trimHistory() {
        let unpinned = items.filter { !$0.isPinned }.sorted { $0.copiedAt > $1.copiedAt }
        guard unpinned.count > Self.maxUnpinnedItems else { return }
        let excess = unpinned.dropFirst(Self.maxUnpinnedItems)
        let excessIDs = Set(excess.map(\.id))
        items.removeAll { excessIDs.contains($0.id) }
        excess.forEach(deleteImageIfUnused)
    }

    private func deleteImageIfUnused(_ item: ClipboardItem) {
        guard let fileName = item.imageFileName,
              !items.contains(where: { $0.imageFileName == fileName }),
              let url = item.imageURL
        else { return }
        try? FileManager.default.removeItem(at: url)
        ThumbnailCache.remove(url)
    }

    /// Saves shortly after changes stop, instead of on every single change.
    private func scheduleSave() {
        saveTask?.cancel()
        saveTask = Task { [weak self] in
            try? await Task.sleep(for: .seconds(1))
            guard let self, !Task.isCancelled else { return }
            self.store.save(self.items)
        }
    }
}
